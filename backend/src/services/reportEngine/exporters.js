import crypto from 'crypto';

export function renderReportHTML(definition) {
  const isSim = definition.is_simulation || definition.environment === 'SIMULATION';
  const watermark = isSim ? '🧪 SIMULATION / LAB DATA ONLY — NOT PRODUCTION' : 'ICS-SHIELD DEFENSIVE SECURITY REPORT';

  return `
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>${definition.title} — ${definition.report_number}</title>
  <style>
    body { font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; background: #0b0f17; color: #f1f5f9; padding: 40px; }
    .header { border-b: 2px solid #38bdf8; padding-bottom: 20px; margin-bottom: 30px; display: flex; justify-content: space-between; }
    .title { font-size: 24px; font-weight: bold; color: #f8fafc; }
    .subtitle { font-size: 14px; color: #38bdf8; font-family: monospace; }
    .banner { padding: 12px; margin-bottom: 25px; font-family: monospace; font-size: 12px; font-weight: bold; border-radius: 6px; }
    .banner-sim { background: rgba(120, 53, 15, 0.4); border: 1px solid #d97706; color: #fcd34d; }
    .banner-live { background: rgba(6, 78, 59, 0.4); border: 1px solid #059669; color: #6ee7b7; }
    .section { margin-bottom: 30px; background: #111827; padding: 20px; border-radius: 8px; border: 1px solid #1e293b; }
    .section-title { font-size: 16px; font-weight: bold; color: #38bdf8; margin-bottom: 12px; font-family: monospace; border-b: 1px solid #1e293b; padding-bottom: 6px; }
    pre { background: #030712; padding: 15px; border-radius: 6px; font-family: monospace; font-size: 11px; color: #38bdf8; overflow-x: auto; }
    .footer { border-t: 1px solid #1e293b; pt: 15px; font-size: 11px; font-family: monospace; color: #64748b; display: flex; justify-content: space-between; }
  </style>
</head>
<body>
  <div class="header">
    <div>
      <div class="title">${definition.title}</div>
      <div class="subtitle">ICS-SHIELD Security Operations Subsystem — ${definition.report_number}</div>
    </div>
    <div style="text-align: right; font-family: monospace; font-size: 11px; color: #94a3b8;">
      <div>ENV: ${definition.environment}</div>
      <div>FORMAT: ${definition.format}</div>
      <div>VER: ${definition.version}</div>
    </div>
  </div>

  <div class="banner ${isSim ? 'banner-sim' : 'banner-live'}">
    ${watermark}
  </div>

  ${definition.sections.map(sec => `
    <div class="section">
      <div class="section-title">${sec.title}</div>
      ${sec.content ? `<p style="font-size: 13px; line-height: 1.6; color: #cbd5e1;">${sec.content}</p>` : ''}
      ${sec.metrics ? `<pre>${JSON.stringify(sec.metrics, null, 2)}</pre>` : ''}
    </div>
  `).join('')}

  <div class="footer">
    <div>Generated By: ${definition.generated_by} • ${new Date(definition.generated_at).toUTCString()}</div>
    <div>Integrity Hash: ${definition.integrity_hash || 'SHA-256 Validated'}</div>
  </div>
</body>
</html>
  `;
}

export function renderReportCSV(definition) {
  const lines = [];
  lines.push(`"Report Number","${definition.report_number}"`);
  lines.push(`"Report Type","${definition.report_type}"`);
  lines.push(`"Title","${definition.title}"`);
  lines.push(`"Environment","${definition.environment}"`);
  lines.push(`"Is Simulation","${definition.is_simulation}"`);
  lines.push(`"Generated By","${definition.generated_by}"`);
  lines.push(`"Generated At","${definition.generated_at}"`);
  lines.push(`"Integrity Hash","${definition.integrity_hash}"`);
  lines.push('');
  lines.push('"Section","Title","Content"');
  definition.sections.forEach(sec => {
    lines.push(`"Section","${sec.title}","${(sec.content || JSON.stringify(sec.metrics || {})).replace(/"/g, '""')}"`);
  });
  return lines.join('\n');
}

export function renderReportJSON(definition) {
  return JSON.stringify(definition, null, 2);
}

export function exportReportContent(definition, exportType = 'PDF') {
  const type = (exportType || 'PDF').toUpperCase();
  let content = '';
  let fileName = `${definition.report_number}.${type.toLowerCase()}`;
  let mimeType = 'application/json';

  if (type === 'PDF') {
    content = renderReportHTML(definition);
    fileName = `${definition.report_number}.html`; // Printable HTML/PDF renderer format
    mimeType = 'text/html';
  } else if (type === 'CSV') {
    content = renderReportCSV(definition);
    fileName = `${definition.report_number}.csv`;
    mimeType = 'text/csv';
  } else {
    content = renderReportJSON(definition);
    fileName = `${definition.report_number}.json`;
    mimeType = 'application/json';
  }

  const hash = crypto.createHash('sha256').update(content).digest('hex');
  const bytes = Buffer.byteLength(content, 'utf8');

  return {
    content,
    fileName,
    mimeType,
    sha256_hash: hash,
    file_size_bytes: bytes,
    export_type: type,
  };
}
