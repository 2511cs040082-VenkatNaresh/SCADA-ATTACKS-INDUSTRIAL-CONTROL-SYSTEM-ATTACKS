CREATE TABLE IF NOT EXISTS network_flows (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    flow_uuid VARCHAR(100) NOT NULL UNIQUE,
    source_asset_id INT NULL,
    destination_asset_id INT NULL,
    source_ip VARCHAR(45) NOT NULL,
    destination_ip VARCHAR(45) NOT NULL,
    source_port INT NOT NULL,
    destination_port INT NOT NULL,
    transport_protocol VARCHAR(20) NOT NULL DEFAULT 'TCP',
    application_protocol VARCHAR(50) NOT NULL DEFAULT 'MODBUS_TCP',
    direction VARCHAR(20) NOT NULL DEFAULT 'INBOUND',
    packet_count INT NOT NULL DEFAULT 1,
    byte_count BIGINT NOT NULL DEFAULT 0,
    first_seen DATETIME(3) NOT NULL,
    last_seen DATETIME(3) NOT NULL,
    duration DOUBLE NOT NULL DEFAULT 0.0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    metadata JSON NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_nf_src_asset FOREIGN KEY (source_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
    CONSTRAINT fk_nf_dst_asset FOREIGN KEY (destination_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
    INDEX idx_nf_assets (source_asset_id, destination_asset_id),
    INDEX idx_nf_ips (source_ip, destination_ip),
    INDEX idx_nf_proto (application_protocol),
    INDEX idx_nf_ts (last_seen)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS protocol_sessions (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    session_uuid VARCHAR(100) NOT NULL UNIQUE,
    source_asset_id INT NULL,
    destination_asset_id INT NULL,
    source_ip VARCHAR(45) NOT NULL,
    destination_ip VARCHAR(45) NOT NULL,
    source_port INT NOT NULL,
    destination_port INT NOT NULL,
    protocol VARCHAR(50) NOT NULL DEFAULT 'MODBUS_TCP',
    start_time DATETIME(3) NOT NULL,
    last_activity DATETIME(3) NOT NULL,
    end_time DATETIME(3) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    request_count INT NOT NULL DEFAULT 0,
    response_count INT NOT NULL DEFAULT 0,
    error_count INT NOT NULL DEFAULT 0,
    exception_count INT NOT NULL DEFAULT 0,
    bytes_sent BIGINT NOT NULL DEFAULT 0,
    bytes_received BIGINT NOT NULL DEFAULT 0,
    average_latency DOUBLE NOT NULL DEFAULT 0.0,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ps_src_asset FOREIGN KEY (source_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
    CONSTRAINT fk_ps_dst_asset FOREIGN KEY (destination_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
    INDEX idx_ps_assets (source_asset_id, destination_asset_id),
    INDEX idx_ps_proto (protocol),
    INDEX idx_ps_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS protocol_transactions (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    session_id BIGINT NULL,
    protocol VARCHAR(50) NOT NULL DEFAULT 'MODBUS_TCP',
    transaction_id VARCHAR(50) NOT NULL,
    source_asset_id INT NULL,
    destination_asset_id INT NULL,
    request_time DATETIME(3) NOT NULL,
    response_time DATETIME(3) NOT NULL,
    latency DOUBLE NOT NULL DEFAULT 0.0,
    operation VARCHAR(100) NOT NULL,
    function_code INT NULL,
    function_name VARCHAR(100) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SUCCESS',
    exception_code INT NULL,
    metadata JSON NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pt_session FOREIGN KEY (session_id) REFERENCES protocol_sessions(id) ON DELETE SET NULL,
    CONSTRAINT fk_pt_src_asset FOREIGN KEY (source_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
    CONSTRAINT fk_pt_dst_asset FOREIGN KEY (destination_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
    INDEX idx_pt_tid (transaction_id),
    INDEX idx_pt_fc (function_code),
    INDEX idx_pt_status (status),
    INDEX idx_pt_ts (request_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS protocol_metrics (
    id INT AUTO_INCREMENT PRIMARY KEY,
    protocol_name VARCHAR(50) NOT NULL,
    metric_key VARCHAR(100) NOT NULL,
    metric_value DOUBLE NOT NULL,
    timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_pm_key_ts (protocol_name, metric_key, timestamp)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
